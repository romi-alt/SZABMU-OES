// Generates docs/role-permissions.md from the single source of truth in packages/shared.
import { writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const { PERMISSIONS, ROLES, ROLE_LABEL, CAMPUS_SCOPED_ROLES } = require('../packages/shared/dist/index.js');
const short = { STUDENT: 'Stu', LECTURER: 'Lec', EXAMINER: 'Exr', CAMPUS_ADMIN: 'Cmp', INVIGILATOR: 'Inv', CCE: 'CCE', SUPER_ADMIN: 'Sup' };
const rows = Object.entries(PERMISSIONS).map(([p, roles]) => `| \`${p}\` | ${ROLES.map((r) => (roles.includes(r) ? '●' : '·')).join(' | ')} |`);
const md = `# Role–permission matrix

> Generated by \`node scripts/gen-permissions-doc.mjs\` from \`packages/shared/src/permissions.ts\`. Do not edit by hand.

Every API route declares exactly one permission (\`@Perm('…')\`) or is explicitly \`@Public()\`. A structural test
(\`apps/api/test/security.test.ts › deny by default\`) fails the build if any route has neither.

## Scope

| Role | Reach |
| --- | --- |
${ROLES.map((r) => `| ${ROLE_LABEL[r]} (\`${r}\`) | ${CAMPUS_SCOPED_ROLES.includes(r) ? '**Campus-scoped** — only institutions assigned in \`user_institutions\`' : 'University-wide (still limited by permission)'} |`).join('\n')}

Campus scope is applied in the service layer via \`scope.filter(user)\` / \`scope.assert(user, institutionId)\`; out-of-scope records
return **404** (existence is not disclosed) or **403** when the caller names an out-of-scope institution explicitly.

## Matrix

| Permission | ${ROLES.map((r) => short[r]).join(' | ')} |
| --- | ${ROLES.map(() => ':-:').join(' | ')} |
${rows.join('\n')}

Legend: Stu=Student, Lec=Lecturer, Exr=Examiner, Cmp=Campus Administrator, Inv=Invigilator, CCE=Controller of Examinations, Sup=Super Administrator.

## Separation of duties (enforced in code, not just in the matrix)

| Control | Rule |
| --- | --- |
| Question review | A reviewer can never approve a question they authored |
| Paper approval | The approver must differ from the person who submitted the paper |
| Result publication | The publisher must differ from the examiner who approved the results |
| Provisioning | Campus admins may only create students, lecturers and invigilators, only inside their own institutions |
| Eligibility | Only attendance-driven eligibility is available to campus admins; **condonation is CCE/Super Admin only** |
| Result visibility | Students: published only. Campus admins: published only. Lecturers: during review, own campus only |
`;
writeFileSync(new URL('../docs/role-permissions.md', import.meta.url), md);
console.log('wrote docs/role-permissions.md');
