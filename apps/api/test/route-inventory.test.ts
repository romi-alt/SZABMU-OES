import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { PATH_METADATA, METHOD_METADATA } from '@nestjs/common/constants';
import { RequestMethod } from '@nestjs/common';
import { Reflector } from '@nestjs/core';
import { AppModule } from '../src/app.module';
import { PERMISSIONS } from '@oes/shared';
import { boot, type Ctx } from './helpers';

/**
 * Authorization coverage guard. Every HTTP route must be explicitly classified as @Public or protected by a @Perm
 * that exists in the permission matrix (the global guard denies anything else only if metadata is missing at RUNTIME —
 * this test makes a missing/incorrect classification a BUILD failure). The reviewed route→permission manifest is
 * committed (docs/route-permissions.md); a new or changed route fails until the manifest is regenerated and reviewed.
 */
let ctx: Ctx;
beforeAll(async () => { ctx = await boot({ studentsPerCampus: 2 }); });
afterAll(async () => { await ctx.app.close(); });

interface RouteInfo { method: string; path: string; perm: string; handler: string }
function routes(): RouteInfo[] {
  const reflector = new Reflector(); const out: RouteInfo[] = [];
  const controllers: (new (...a: never[]) => object)[] = Reflect.getMetadata('controllers', AppModule) ?? [];
  for (const cls of controllers) {
    const base = String(Reflect.getMetadata(PATH_METADATA, cls) ?? '');
    for (const name of Object.getOwnPropertyNames(cls.prototype)) {
      if (name === 'constructor') continue;
      const fn = (cls.prototype as Record<string, unknown>)[name] as (...a: unknown[]) => unknown;
      if (typeof fn !== 'function') continue;
      const m = Reflect.getMetadata(METHOD_METADATA, fn); if (m === undefined) continue;
      const sub = String(Reflect.getMetadata(PATH_METADATA, fn) ?? '');
      const pub = reflector.getAllAndOverride<boolean>('public', [fn, cls]); const perm = reflector.getAllAndOverride<string>('perm', [fn, cls]);
      out.push({ method: RequestMethod[m]!, path: ('/api/' + [base, sub].filter(Boolean).join('/')).replace(/\/+/g, '/').replace(/(.)\/$/, '$1'), perm: pub ? 'PUBLIC' : perm ?? 'AUTHENTICATED-ONLY(no @Perm)', handler: `${cls.name}.${name}` });
    }
  }
  return out.sort((a, b) => (a.path + a.method).localeCompare(b.path + b.method));
}

describe('authorization coverage', () => {
  it('every route is @Public or carries a @Perm that exists in the permission matrix', () => {
    const rs = routes(); expect(rs.length).toBeGreaterThan(80);
    const unclassified = rs.filter((r) => r.perm.startsWith('AUTHENTICATED-ONLY'));
    // Only the explicitly reviewed self-service routes may rely on authentication alone.
    const allowedAuthOnly = new Set(['AuthController.logout', 'AuthController.me', 'AuthController.changePassword', 'AuthController.profile']);
    const bad = unclassified.filter((r) => !allowedAuthOnly.has(r.handler));
    expect(bad, `routes with no @Perm/@Public: ${bad.map((b) => b.method + ' ' + b.path).join(', ')}`).toEqual([]);
    for (const r of rs) if (r.perm !== 'PUBLIC' && !r.perm.startsWith('AUTHENTICATED-ONLY')) expect(Object.keys(PERMISSIONS), `${r.handler} uses unknown permission ${r.perm}`).toContain(r.perm);
  });

  it('public routes are exactly the reviewed unauthenticated surface', () => {
    const pub = routes().filter((r) => r.perm === 'PUBLIC').map((r) => `${r.method} ${r.path}`);
    expect(pub).toEqual(expect.arrayContaining(['POST /api/auth/login', 'GET /api/health']));
    expect(pub.sort()).toMatchInlineSnapshot(`
      [
        "GET /api/health",
        "GET /api/metrics",
        "GET /api/public/verify",
        "POST /api/auth/forgot",
        "POST /api/auth/login",
        "POST /api/auth/register",
        "POST /api/auth/register/verify",
        "POST /api/auth/reset",
        "POST /api/auth/verify-code",
      ]
    `);
  });

  it('the committed route→permission manifest matches the code (review required when it changes)', () => {
    const rs = routes();
    const md = ['# Route → permission manifest', '', '_Generated by `apps/api/test/route-inventory.test.ts` (set `UPDATE_ROUTE_MANIFEST=1` to regenerate). A new or changed route fails CI until this file is regenerated and reviewed._', '',
      '| Method | Path | Permission | Handler |', '| --- | --- | --- | --- |', ...rs.map((r) => `| ${r.method} | \`${r.path}\` | ${r.perm === 'PUBLIC' ? '**PUBLIC**' : '`' + r.perm + '`'} | ${r.handler} |`), ''].join('\n');
    const file = path.resolve(__dirname, '../../../docs/route-permissions.md');
    if (process.env.UPDATE_ROUTE_MANIFEST === '1') writeFileSync(file, md);
    expect(readFileSync(file, 'utf8')).toBe(md);
  });
});
